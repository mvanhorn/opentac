def log(msg):
    print(msg, flush=True)


def generate(outline, **params):
    """One OpenTac-CAD generate, as the web app runs it. Returns (svg, manifest, stats, drc)."""
    from opentac.cad import main
    params.setdefault("board_mode", "expand")
    params.setdefault("router", "hug")
    resp = main.generate(main.GenerateRequest(outline=outline, **params))
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(resp.zip_b64))) as zf:
        man = json.loads(zf.read("manifest.json"))
    return resp.svg, man, resp.stats, resp.drc


def svg_parts(svg):
    """(viewBox w, h, style block, body) of an OpenTac-CAD preview SVG."""
    vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
    style = re.search(r"<style>.*?</style>", svg, re.S).group(0)
    body = svg[svg.index("</style>") + len("</style>"):svg.rindex("</svg>")]
    return float(vb.group(1)), float(vb.group(2)), style, body


def polygon(svg, cls):
    pts = re.search(rf'<polygon points="([^"]+)" class="{cls}"', svg).group(1)
    return np.array([[float(v) for v in p.split(",")] for p in pts.split()])


def save_raster(fig, path, quality=86):
    """A matplotlib figure as a JPEG (photographic) or PNG (flat colours)."""
    from PIL import Image
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=fig.dpi, facecolor=fig.get_facecolor(), bbox_inches="tight",
                pad_inches=0.06)
    buf.seek(0)
    im = Image.open(buf).convert("RGB")
    if path.suffix == ".jpg":
        im.save(path, quality=quality, optimize=True, progressive=True)
    else:
        im = im.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        im.save(path, optimize=True)
    log(f"wrote {path} ({path.stat().st_size // 1024} KB, {im.size[0]}x{im.size[1]})")


def write(path, text):
    path.write_text(text)
    log(f"wrote {path} ({path.stat().st_size // 1024} KB)")


