def fig_sim():
    """Foam model: three of the paper's indenters pressed into a CAD-generated skin."""
    plt = mpl()
    from opentac import manifest as manifest_mod
    from opentac.sim import Sensor

    _, man, stats, _ = generate(SIM_RECT, pixel_w_mm=1.8, pixel_h_mm=1.8, pitch_x_mm=2.0, pitch_y_mm=2.0)
