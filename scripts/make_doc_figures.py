def learn_skin(skin_id):
    skins = json.loads((TAKES / "skins.json").read_text())
    return skins[skin_id]


def skin_manifest(s):
    """A drawable manifest for a skin of docs/learn/data/skins.json.

    skins.json keeps each taxel's position, size, outline and shear groups, which is
    what opentac view draws; it does not keep the scan rows and columns. Those are
    numbered here from the grid position (the viewer does not use them), and the
    taxels are put in row-major order, with the frame values permuted to match."""
    xy = np.asarray(s["xy"], float)
    p = float(s["pitch"])
    col = np.rint((xy[:, 0] - xy[:, 0].min()) / p).astype(int)
    row = np.rint((xy[:, 1].max() - xy[:, 1]) / p).astype(int)
    order = np.lexsort((col, row))
    pixels = [[float(xy[k, 0]), float(xy[k, 1]), int(row[k]), int(col[k])] for k in order]
    b = np.asarray(s["b"], int)[order] if s.get("b") else None
    raw = {"v": 5, "name": s["label"], "pixels": pixels, "w": s["w"], "h": s["h"],
           "outline": s["outline"]}
    if b is not None and len(s.get("bumps") or []):
        raw["shear"] = {"bumps": s["bumps"], "b": b.tolist()}
    return raw, order


def fig_view():
    """opentac view's own snapshot drawing of one recorded frame."""
    plt = mpl()
    from opentac import manifest as manifest_mod
    from opentac import view as view_mod

    take = json.loads((TAKES / "takes" / "20260922_164112_square.json").read_text())
    skin = learn_skin(take["skin"])
    raw, order = skin_manifest(skin)
    m = manifest_mod.load(raw)
    frames = np.asarray(take["raw"], float)
    # the viewer's zero (key b): the mean of the last frames with nothing touching
    zero = frames[max(0, take["onset"] - view_mod.BASELINE_FRAMES):take["onset"]].mean(axis=0)
    values = np.clip(frames[take["peak"]] - zero, 0, None)[order]

    fig, ax = plt.subplots(figsize=(4.6, 5.0), dpi=200)
    panel = view_mod.Panel(ax, m, skin["label"])            # the title is the manifest's name
    panel.draw(values, note=f"peak {np.nanmax(values):.0f}  (zeroed)")
    fig.tight_layout()
    save_raster(fig, OUT / "view_frame.jpg")
    plt.close(fig)
    log(f"  view: take {take['take']}, frame {take['first_frame'] + take['peak']}, "
        f"object {take['object']}, skin {skin['label']}")


