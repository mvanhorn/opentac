def footprint_at(text, ref):
    """(x, y, block) of the footprint with reference `ref` in a .kicad_pcb text."""
    for m in re.finditer(r'\(footprint "', text):
        depth, i = 0, m.start()
        while True:                                  # the footprint's whole block
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
            if depth == 0:
                break
        fp = text[m.start():i]
        if f'"Reference" "{ref}"' in fp:
            x, y = (float(v) for v in re.search(r"\(at ([-\d.]+) ([-\d.]+)", fp).groups()[:2])
            return x, y, fp
    raise KeyError(ref)


def board_with_rings(key, refs, radius_mm=3.2):
    """A top-view KiCad render of a readout board with an amber ring round each part in `refs`."""
    from PIL import Image, ImageChops, ImageDraw
    if not (HW / "libs" / "3dmodels").is_dir():
        sys.exit("hardware/libs/3dmodels is missing (see hardware/README.md, 3D models)")
    pcb, libs, _ = BOARDS[key]
    bare = pcb.read_text()
    text = bare.replace(libs, str(HW / "libs"))
    rings = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "board.kicad_pcb").write_text(text)
        shutil.copy(pcb.with_suffix(".kicad_pro"), tmp / "board.kicad_pro")
        kicad_render(tmp / "board.kicad_pcb", tmp / "board.png", w=1800, h=1800)
        a = Image.open(tmp / "board.png").convert("RGBA")
        # Where each part lands in the picture: render a copy with a ring round it on the
        # top silkscreen, and one without; the two differ only at the ring. This pass uses
        # the deterministic OpenGL render and no part models (their paths do not resolve
        # from the temporary folder), so no part hides the ring.
        (tmp / "plain.kicad_pcb").write_text(bare)
        shutil.copy(pcb.with_suffix(".kicad_pro"), tmp / "plain.kicad_pro")
        kicad_render(tmp / "plain.kicad_pcb", tmp / "plain.png", w=1800, h=1800, quality="basic")
        pa = Image.open(tmp / "plain.png").convert("RGB")
        for ref in refs:
            x, y, fp = footprint_at(bare, ref)
            ring = (f'\t(gr_circle (center {x} {y}) (end {x + radius_mm} {y}) '
                    f'(stroke (width 0.5) (type solid)) (fill no) (layer "F.SilkS"))\n')
            (tmp / "marked.kicad_pcb").write_text(bare[:bare.rindex(")")] + ring + ")\n")
            shutil.copy(pcb.with_suffix(".kicad_pro"), tmp / "marked.kicad_pro")
            kicad_render(tmp / "marked.kicad_pcb", tmp / "marked.png", w=1800, h=1800, quality="basic")
            diff = ImageChops.difference(pa, Image.open(tmp / "marked.png").convert("RGB")).convert("L")
            # fit a circle to the ring's pixels (part of it can fall off the board edge)
            ys, xs = np.nonzero(np.asarray(diff) > 40)
            A = np.c_[2 * xs, 2 * ys, np.ones(len(xs))]
            (cx, cy, c0), *_ = np.linalg.lstsq(A, xs ** 2 + ys ** 2, rcond=None)
            rings.append((cx, cy, float(np.sqrt(c0 + cx ** 2 + cy ** 2)) * 1.05))
            log(f"  {key} {ref} at ({x}, {y}) mm")
    abox = a.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    box = (min([abox[0]] + [cx - r for cx, cy, r in rings]), min([abox[1]] + [cy - r for cx, cy, r in rings]),
           max([abox[2]] + [cx + r for cx, cy, r in rings]), max([abox[3]] + [cy + r for cx, cy, r in rings]))
    m_ = int(0.03 * max(box[2] - box[0], box[3] - box[1]))
    crop = tuple(int(v) for v in (box[0] - m_, box[1] - m_, box[2] + m_, box[3] + m_))
    im = on_white(a.crop(crop))
    d = ImageDraw.Draw(im)
    lw = max(5, im.width // 140)
    for cx, cy, r in rings:
        cx, cy = cx - crop[0], cy - crop[1]
        d.ellipse((cx - r, cy - r, cx + r, cy + r), outline=AMBER, width=lw)
    return im


def side_by_side(shots, path, H=760):
    """Pictures at one height, each named under it, saved as a JPEG."""
    from PIL import Image, ImageDraw, ImageFont
    ims = [im.resize((round(im.width * H / im.height), H), Image.LANCZOS) for im, _ in shots]
    gap, foot = 60, 70
    W = sum(i.width for i in ims) + gap * (len(ims) - 1)
    out = Image.new("RGB", (W, H + foot), "white")
    d = ImageDraw.Draw(out)
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 34)
    except OSError:
        font = ImageFont.load_default()
    x = 0
    for im, (_, label) in zip(ims, shots):
        out.paste(im, (x, 0))
        tw = d.textlength(label, font=font)
        d.text((x + (im.width - tw) / 2, H + 18), label, fill=INK, font=font)
        x += im.width + gap
    out.save(path, quality=80, optimize=True, progressive=True)
    log(f"wrote {path} ({path.stat().st_size // 1024} KB, {out.size[0]}x{out.size[1]})")


