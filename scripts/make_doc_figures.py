def fig_sim_bumps():
    """Bump model: shear per bump after turning a 250 mm ball by 1 degree (sim.md's example)."""
    plt = mpl()
    from opentac import manifest as manifest_mod
    from opentac.sim import Sensor

    m = manifest_mod.load(FIX / "flat_square.json")
    s = Sensor(m, model="mujoco")
    angles = [0, 0.25, 0.5, 1, 2]
    frames = s.twist(angles, force_n=8.0, radius_mm=250.0)
    before = s.decode_shear(frames[0])
    after = s.decode_shear(frames[3]) - before          # what the 1 degree turn added
    xy = np.asarray(s.bump_xy_mm)
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.1), dpi=200)
    vmax = max(float(np.nanmax(frames[0].taxels)), float(np.nanmax(frames[3].taxels)))
    spacing = float(np.median(np.sort(np.linalg.norm(xy[:, None] - xy[None], axis=2), axis=1)[:, 1]))
    scale = max(np.abs(before).max(), np.abs(after).max()) / (0.8 * spacing)   # N per mm of arrow
    for ax, f, title, sh in [(axes[0], frames[0], "Pressed, 8 N", before),
                             (axes[1], frames[3], "Then turned 1°: what the turn added", after)]:
        pc = draw_taxels(ax, m.xy, m.w, m.h, f.taxels, "magma", 0, vmax, m.raw.get("outline"))
        ax.plot(xy[:, 0], xy[:, 1], "o", ms=2, color="#39ff6a")
        ax.quiver(xy[:, 0], xy[:, 1], sh[:, 0], sh[:, 1], color="#39ff6a", angles="xy",
                  scale_units="xy", scale=scale, width=0.012, edgecolor="black", linewidth=0.4)
        ax.set_title(title, pad=4)
        ax.set_xticks([]); ax.set_yticks([])
        ax.set_facecolor("#0b0e12")
        for sp in ax.spines.values():
            sp.set_visible(False)
    cb = fig.colorbar(pc, ax=axes, fraction=0.03, pad=0.02)
    cb.set_label("N per taxel")
    save_raster(fig, OUT / "sim_bumps.jpg")
    plt.close(fig)
    log(f"  bumps: max shear added by 1 deg {np.abs(after).max():.2f} N; "
        f"before the turn {np.abs(before).max():.2f} N")


def fig_profiles():
    """The two readout profiles: counts per taxel against force, at 2 and 4 mm pitch."""
    plt = mpl()
    from opentac.sim.readout import Readout
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9), dpi=200, sharey=True)
    for ax, pitch_mm, fmax in zip(axes, (2.0, 4.0), (3.0, 6.0)):
        pitch = pitch_mm / 1000.0
        for name, colour in (("v2", ROW), ("v3", AMBER_DARK)):
            r = Readout.from_profile(name)
            f = np.linspace(0, fmax, 600)
            c = r.counts(f, pitch)
            inside = ~r.extrapolating(f, pitch)
            ax.plot(f[inside], c[inside], color=colour, lw=1.6, label=f'"{name}": {r.material}')
            ax.plot(f[~inside], c[~inside], color=colour, lw=1.2, ls=(0, (3, 2)))
            log(f"  {name} at {pitch_mm:g} mm: ADC maximum at {r.saturation_force_n(pitch):.3f} N per taxel")
        ax.axhline(r.adc_max, color="#8a949e", lw=0.7, ls=":")
        ax.set_title(f"{pitch_mm:g} mm pitch", pad=4)
        ax.set_xlabel("force on one taxel (N)")
        ax.grid(color="#e3e6ea", lw=0.5)
        ax.set_axisbelow(True)
    axes[0].set_ylabel("counts above baseline")
    axes[0].text(fmax * 0.98 / 2, r.adc_max - 90, f"ADC maximum, {r.adc_max:.0f}", fontsize=7, color=MUTED,
                 va="top", ha="right")
    axes[1].legend(frameon=False, fontsize=7.5, loc="lower right")
    fig.tight_layout()
    save_raster(fig, OUT / "sim_readout_profiles.png")
    plt.close(fig)


