def fig_ffc():
    """Flat-cable contact types: same side (A) when both connectors face one way, opposite side (B) otherwise."""
    b = []
    HOUS = 'fill="#e8e3d8" stroke="#8a8170"'
    CW, CH, SW, SH = 104, 40, 78, 16          # connector and slot, drawn large

    def zif(x, y_board, below=False, opens_left=False):
        """A ZIF connector on a board, side view, its contact on the board side of the slot."""
        y = y_board + 14 if below else y_board - CH
        out = [f'<rect x="{x}" y="{y}" width="{CW}" height="{CH}" rx="3" {HOUS}/>']
        sy = y + CH / 2
        sx = x if opens_left else x + CW - SW
        out.append(f'<rect x="{sx}" y="{sy - SH / 2}" width="{SW}" height="{SH}" fill="white" '
                   f'stroke="#8a8170" stroke-width="0.8"/>')
        cy = sy - SH / 2 - 1 if below else sy + SH / 2 - 3   # the connector's contact, board side
        out.append(f'<rect x="{sx + 14}" y="{cy}" width="{SW - 28}" height="4" fill="#9a7a10"/>')
        return out, sy, sx

    def cable_end(x0, x1, y, contacts_down):
        out = [f'<rect x="{x0}" y="{y - 3}" width="{x1 - x0}" height="6" fill="#b8b0a0"/>']
        out.append(f'<rect x="{x0 + 4}" y="{y + 3 if contacts_down else y - 7}" width="{x1 - x0 - 8}" height="4" fill="{GOLD}"/>')
        return out

