def fig_transfer_steps():
    """How OpenTac-Transfer resamples: A's cells placed on B, cut into sub-cells, binned into B's."""
    plt = mpl()
    from matplotlib.patches import Polygon, Rectangle
    from opentac import manifest as manifest_mod
    from opentac.transfer import Transfer, Layout

    a = manifest_mod.load(FIX / "grid_4mm.json")
    b = manifest_mod.load(FIX / "flat_square.json")
    la, lb = Layout(a), Layout(b)
    angle = 20.0
    shift = lb.centroid - la.centre                     # A's centre on B's centroid, then turned
    tr = Transfer(la, lb, angle_deg=angle, shift_mm=shift)
    # the same sub-cells Transfer() bins (opentac/transfer.py, kernel "box")
    s = max(4, int(np.ceil(4 * la.pitch / lb.pitch)))
    u = (np.arange(s) + 0.5) / s - 0.5
    du, dv = np.meshgrid(u, u)
    offs = np.stack([du.ravel(), dv.ravel()], 1) * la.pitch
    th = np.deg2rad(angle)
    rot = np.array([[np.cos(th), -np.sin(th)], [np.sin(th), np.cos(th)]])

    def place(p):
        return (p - la.centre) @ rot.T + la.centre + shift

    corners = np.array([[-.5, -.5], [.5, -.5], [.5, .5], [-.5, .5]]) * la.pitch
    fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.6), dpi=200)
    # two of A's cells: one wholly over B, and one whose shares partly fall off B's edge
    inner = int(np.argmin(np.where(tr.kept > 0.999, np.linalg.norm(la.xy - la.centre, axis=1), np.inf)))
    part = np.flatnonzero((tr.kept > 0.3) & (tr.kept < 0.7))
    edge = int(part[np.argmin(np.linalg.norm(la.xy[part] - la.xy[inner], axis=1))])
    pick = [inner, edge]
    cmap = plt.get_cmap("tab20")
    for ax in axes:
        for j, (x, y) in enumerate(lb.xy):
            ax.add_patch(Rectangle((x - lb.pitch / 2, y - lb.pitch / 2), lb.pitch, lb.pitch,
                                   fc="#eef3fb", ec="#6688aa", lw=0.5))
        for k, c in enumerate(la.xy):
            ax.add_patch(Polygon(place(c + corners), closed=True, fc="none",
                                 ec=AMBER if k in pick else "#c9a46a", lw=1.2 if k in pick else 0.5))
        ax.set_aspect("equal")
        ax.set_xticks([]); ax.set_yticks([])
        for sp in ax.spines.values():
            sp.set_visible(False)
    allp = np.vstack([place(c + corners) for c in la.xy])
    axes[0].set_xlim(allp[:, 0].min() - 1, allp[:, 0].max() + 1)
    axes[0].set_ylim(allp[:, 1].min() - 1, allp[:, 1].max() + 1)
    axes[0].set_title(f"1. A's {la.pitch:g} mm cells placed on B's {lb.pitch:g} mm cells", pad=4)
    ax = axes[1]
    for k in pick:
        pts = place(la.xy[k] + offs)
        idx = lb.index_of(pts)
        for p_, j in zip(pts, idx):
            if j >= 0:
                ax.plot(*p_, "o", ms=2.6, color=cmap(j % 20), mec="none")
            else:
                ax.plot(*p_, "x", ms=2.6, color=INK, mew=0.7)
    zone = np.vstack([place(la.xy[k] + corners) for k in pick])
    ax.set_xlim(zone[:, 0].min() - 1.5, zone[:, 0].max() + 1.5)
    ax.set_ylim(zone[:, 1].min() - 1.5, zone[:, 1].max() + 1.5)
    ax.set_title(f"2. {s}×{s} shares per cell, each to the B cell under it;\n3. shares with no B taxel under them are dropped (×)", pad=4)
    fig.tight_layout()
    save_raster(fig, OUT / "transfer_steps.png")
    plt.close(fig)
    log(f"  transfer steps: s = {s}, shares kept by the two cells {tr.kept[pick].round(3)}")


