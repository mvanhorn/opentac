def draw_taxels(ax, xy, w, h, values, cmap, vmin, vmax, outline=None, edge="none"):
    """Taxels as squares where they sit, coloured by value: the way opentac view draws them."""
    from matplotlib.collections import PatchCollection
    from matplotlib.patches import Rectangle
    pc = PatchCollection([Rectangle((x - w / 2, y - h / 2), w, h) for x, y in xy],
                         cmap=cmap, edgecolor=edge, linewidth=0.3)
    pc.set_array(np.asarray(values, float))
    pc.set_clim(vmin, vmax)
    ax.add_collection(pc)
    if outline is not None and len(outline):
        o = np.vstack([outline, outline[:1]])
        ax.plot(o[:, 0], o[:, 1], color="0.6", lw=0.8)
    pts = np.vstack([xy] + ([np.asarray(outline)] if outline is not None and len(outline) else []))
    pad = max(w, h)
    ax.set_xlim(pts[:, 0].min() - pad, pts[:, 0].max() + pad)
    ax.set_ylim(pts[:, 1].min() - pad, pts[:, 1].max() + pad)
    ax.set_aspect("equal")
    return pc


