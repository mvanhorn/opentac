def fig_settings():
    """The Yubi finger pad example, with the cable edge, tail, connector and one taxel named."""
    svg, man, stats, drc = generate(YUBI, **GRID_3MM)
    log(f"  yubi: {stats['total_pixels']} taxels, {man['r']} rows x {man['c']} cols, "
        f"{stats['connector_pos']}-position connector, DRC {drc['violations']}, tail "
        f"{stats.get('tail_length_mm')} mm ({stats.get('tail_length_reason')})")
    w, h, style, body = svg_parts(svg)
    so = polygon(svg, "sensor-outline")
    a, b = so[0], so[1]                                  # the cable edge
    pad_y = float(re.search(r'<line x1="0" y1="([\d.]+)"[^>]*class="pad-line"', svg).group(1))
    outline = polygon(svg, "outline")
    tail = outline[outline[:, 1] > a[1] + 1.0]
    tail_x = (tail[:, 0].min() + tail[:, 0].max()) / 2 if len(tail) else (a[0] + b[0]) / 2
    rects = [tuple(float(v) for v in r) for r in re.findall(
        r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" class="pixel"', svg)]
    rx, ry, rw, rh = max(rects, key=lambda r: r[0] - 0.6 * r[1])   # a taxel at the upper right

    def route(cls):
        lines = [np.array([[float(v) for v in q.split(",")] for q in pts.split()]) for pts in
                 re.findall(rf'<polyline points="([^"]+)" class="{cls}"', svg)]
        return max(lines, key=lambda L: L[:, 0].max())             # the rightmost one

    col, row = route("col-route"), route("row-route")
    def at_y(L, y0):
        for p0, p1 in zip(L[:-1], L[1:]):
            if (p0[1] - y0) * (p1[1] - y0) <= 0 and p0[1] != p1[1]:
                t = (y0 - p0[1]) / (p1[1] - p0[1])
                return p0 + t * (p1 - p0)
        return L[-1]

    col_pt = at_y(col, a[1] - 1.8)                                   # just above the cable edge
    row_pt = row[np.argmin(np.abs(row[:, 1] - (ry + a[1]) / 2))]     # beside the taxel field
    R = w + 7                                                        # label column
    ann = [f'<line x1="{a[0]:.2f}" y1="{a[1]:.2f}" x2="{b[0]:.2f}" y2="{b[1]:.2f}" class="cable-edge"/>']

    def label(y, title, sub, tx, ty):
        ann.append(f'<line x1="{R - 1.0:.2f}" y1="{y - 1.0:.2f}" x2="{tx:.2f}" y2="{ty:.2f}" class="lead"/>'
                   f'<circle cx="{tx:.2f}" cy="{ty:.2f}" r="0.6" class="dot"/>'
                   f'<text x="{R:.2f}" y="{y:.2f}" class="lab">{title}</text>'
                   f'<text x="{R:.2f}" y="{y + 3.5:.2f}" class="sub">{sub}</text>')

    tail_mid = (a[1] + pad_y) / 2
    label(ry + rh / 2 + 1, "Taxel", f"{man['w']:g} mm on a {GRID_3MM['pitch_x_mm']:g} mm pitch",
          rx + rw * 0.75, ry + rh / 2)
    label(ry + (a[1] - ry) * 0.40, "Rows", "bottom copper (blue, dashed)", row_pt[0], row_pt[1])
    label(ry + (a[1] - ry) * 0.62, "Columns", "top copper (red)", col_pt[0], col_pt[1])
    label(a[1] - 3.5, "Cable edge", "where the tail leaves the outline", max(a[0], b[0]) - 0.5, a[1])
    tail_len = stats.get("tail_length_mm")
    auto = " (automatic)" if stats.get("tail_length_auto") else ""
    label(tail_mid + 1.5, "Tail", f"{tail_len:g} mm{auto}, cut down to its traces", tail_x + 3.0, tail_mid)
    label(pad_y + 6.5, "Connector end", f"{stats['connector_pos']} positions, 0.5 mm pitch",
          tail_x + 4.0, pad_y + 1.2)
    W = R + 52
    style = style.replace(
        "</style>",
        f"  .cable-edge {{ stroke: {AMBER}; stroke-width: 1.1; stroke-linecap: round; }}\n"
        f"  .lead {{ stroke: {MUTED}; stroke-width: 0.2; }}\n"
        f"  .dot {{ fill: {INK}; }}\n"
        f"  .lab {{ font: 600 3.0px {FONT}; fill: {INK}; }}\n"
        f"  .sub {{ font: 2.6px {FONT}; fill: {MUTED}; }}\n</style>")
    H = max(h, pad_y + 12)
    out = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.2f} {H:.2f}" '
           f'width="{W * 9:.0f}" height="{H * 9:.0f}">\n{style}\n'
           f'<rect width="100%" height="100%" fill="white"/>\n{body}\n' + "\n".join(ann) + "\n</svg>\n")
    write(OUT / "design_settings.svg", out)


